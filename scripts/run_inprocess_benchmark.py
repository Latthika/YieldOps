"""Measure the local FastAPI request path without opening a network socket."""

from __future__ import annotations

import argparse
import json
import math
import time
from pathlib import Path

from fastapi.testclient import TestClient

from yieldops.api import main as api
from yieldops.telemetry.prometheus import PrometheusMetrics
from yieldops.telemetry.store import InMemoryTelemetryStore

ROOT = Path(__file__).resolve().parents[1]


def _percentile(values: list[float], percentile: float) -> float | None:
    if not values:
        return None
    ordered = sorted(values)
    return ordered[max(1, math.ceil(percentile * len(ordered))) - 1]


def run(*, requests: int, repetitions: int) -> dict[str, object]:
    if requests < 1 or repetitions < 1:
        raise ValueError("requests and repetitions must be positive")
    trials = []
    for repetition in range(repetitions):
        api.telemetry_store = InMemoryTelemetryStore()
        api.prometheus_metrics = PrometheusMetrics()
        client = TestClient(api.app)
        for warmup in range(5):
            client.post(
                "/v1/inference",
                json={"prompt": f"warmup {warmup}", "model_name": "yieldops-simulator"},
            ).raise_for_status()

        client_ms: list[float] = []
        simulated_ms: list[float] = []
        successes = 0
        started_run = time.perf_counter()
        for index in range(requests):
            started_request = time.perf_counter()
            response = client.post(
                "/v1/inference",
                json={
                    "prompt": f"synthetic benchmark request {index}",
                    "model_name": "yieldops-simulator",
                    "task_category": "classification",
                    "max_output_tokens": 8,
                },
            )
            client_ms.append((time.perf_counter() - started_request) * 1_000)
            if response.status_code == 200:
                successes += 1
                telemetry = response.json()["telemetry"]
                if telemetry["provenance"] == "simulated":
                    simulated_ms.append(telemetry["end_to_end_latency_ms"])
        elapsed = time.perf_counter() - started_run
        trials.append(
            {
                "repetition": repetition + 1,
                "requested": requests,
                "successful": successes,
                "errors": requests - successes,
                "elapsed_seconds": elapsed,
                "requests_per_second": successes / elapsed if elapsed else None,
                "client_testclient_latency_ms": {
                    "provenance": "measured",
                    "p50": _percentile(client_ms, 0.50),
                    "p95": _percentile(client_ms, 0.95),
                    "p99": _percentile(client_ms, 0.99),
                },
                "backend_inference_latency_ms": {
                    "provenance": "simulated",
                    "p50": _percentile(simulated_ms, 0.50),
                    "p95": _percentile(simulated_ms, 0.95),
                    "p99": _percentile(simulated_ms, 0.99),
                },
            }
        )
        client.close()

    result = {
        "benchmark": "FastAPI TestClient in-process request-path smoke benchmark",
        "host": "Apple M4, 16 GB RAM, macOS 15.6.1, Python 3.12.16",
        "configuration": {"requests_per_repetition": requests, "repetitions": repetitions},
        "limitations": [
            "No socket or network path is included; TestClient invokes the ASGI app in-process.",
            "Inference output and backend latency remain deterministic simulation.",
            "This measures local application-path overhead, not production capacity or model speed.",
        ],
        "trials": trials,
    }
    config_path = ROOT / "experiments" / "configs" / "milestone_2_inprocess.json"
    result_path = ROOT / "experiments" / "results" / "milestone_2_inprocess_benchmark.json"
    report_path = ROOT / "experiments" / "results" / "milestone_2_inprocess_benchmark.md"
    config_path.parent.mkdir(parents=True, exist_ok=True)
    result_path.parent.mkdir(parents=True, exist_ok=True)
    config_path.write_text(
        json.dumps(result["configuration"], indent=2, sort_keys=True) + "\n"
    )
    result_path.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    _write_report(report_path, result)
    return result


def _write_report(path: Path, result: dict[str, object]) -> None:
    lines = [
        "# Milestone 2 In-Process Benchmark",
        "",
        "Generated by `scripts/run_inprocess_benchmark.py`; see the JSON beside this report for full precision.",
        "",
        f"Host: {result['host']}.",
        "The observed request path is measured through FastAPI `TestClient` (in-process).",
        "The backend inference latency is simulated and is not timed model execution.",
        "",
        "| Trial | Successes | Errors | Requests/s | TestClient P50/P95/P99 ms | Simulated server P50/P95/P99 ms |",
        "|---:|---:|---:|---:|---:|---:|",
    ]
    for trial in result["trials"]:
        client = trial["client_testclient_latency_ms"]
        server = trial["backend_inference_latency_ms"]
        lines.append(
            f"| {trial['repetition']} | {trial['successful']} | {trial['errors']} | "
            f"{trial['requests_per_second']:.1f} | "
            f"{client['p50']:.3f}/{client['p95']:.3f}/{client['p99']:.3f} | "
            f"{server['p50']:.1f}/{server['p95']:.1f}/{server['p99']:.1f} |"
        )
    lines += ["", "## Limits", ""]
    lines.extend(f"- {limit}" for limit in result["limitations"])
    lines.append("")
    path.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--requests", type=int, default=100)
    parser.add_argument("--repetitions", type=int, default=3)
    args = parser.parse_args()
    print(json.dumps(run(requests=args.requests, repetitions=args.repetitions), indent=2))


if __name__ == "__main__":
    main()
